/**
 * Emits the files the `agent-kit` and `agent-kit-hooks` registry items install
 * into a consumer app. Called from the contract emit/drift loop in
 * `contract-emit.test.ts`, so `pnpm contract:emit` writes them and `pnpm test`
 * fails on any byte of drift.
 *
 * The engine ships as byte copies of `packages/ds-rules`; only data
 * (`rules.json`, scopes rewritten) and the rules prose are rendered here.
 * Spec: docs/superpowers/specs/2026-11-06-consumer-guardrails.md §4.
 */
import { readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { CONSUMER_RULES, CONSUMER_RULES_INTRO, type ConsumerRule } from "../../lib/consumer-rules";

const REPO_ROOT = resolve(__dirname, "../../../..");
const RULES_DIR = "packages/ds-rules/rules";
export const KIT_DIR = "registry/agent-kit";

/** The subset of a ds-rules record this emitter reads and rewrites. */
export interface KitRule {
  id: string;
  title: string;
  severity: "blocker" | "review" | "warning";
  detect: { method: string; scope?: string[]; [key: string]: unknown };
  [key: string]: unknown;
}

/** Installed path under the kit (keyed) to its repo source, copied byte for byte. */
export const KIT_SOURCES: Record<string, string> = {
  "scripts/super-ai/validate.mjs": "packages/ds-rules/consumer/validate.mjs",
  "scripts/super-ai/rulecheck.mjs": "packages/ds-rules/rulecheck.mjs",
  "scripts/super-ai/system-diff.mjs": "packages/ds-rules/consumer/system-diff.mjs",
  "scripts/super-ai/src/token-rules.mjs": "packages/ds-rules/src/token-rules.mjs",
  "scripts/super-ai/src/motion-rules.mjs": "packages/ds-rules/src/motion-rules.mjs",
};

/** Repo scope to consumer folder. A scope missing here throws, so a scope the
 *  gate gains later cannot silently vanish from consumers. */
const SCOPE_MAP: Record<string, string> = {
  "apps/docs/registry/super-ai": "components/super-ai",
  "apps/docs/registry/marketing": "components/marketing",
  "apps/docs/components": "components",
  "apps/docs/app": "app",
};

export function consumerRules(records: KitRule[]): KitRule[] {
  return records
    .filter((r) => r.detect.method === "grep" || r.detect.method === "heuristic")
    .map((r) => ({
      ...r,
      detect: {
        ...r.detect,
        scope: (r.detect.scope ?? []).flatMap((s) => {
          const mapped = SCOPE_MAP[s];
          if (!mapped) throw new Error(`unmapped scope ${s}`);
          return [mapped, `src/${mapped}`];
        }),
      },
    }));
}

export function renderAgentsFile(rules: readonly ConsumerRule[]): string {
  const parts = [
    "<!-- Generated by Super AI Components agent-kit. Do not edit; reinstall to update. -->",
    "",
    "# Super AI Components: rules for agents",
    "",
    CONSUMER_RULES_INTRO,
    "",
  ];
  for (const r of rules) parts.push(`## ${r.n}. ${r.title}`, "", r.body, "", `Why: ${r.why}`, "");
  parts.push(
    "## Where to look",
    "",
    "1. `components/super-ai/index.toon`: one line per item, to find the one that fits.",
    "2. `components/super-ai/<name>.meta.json`: the contract of an installed item.",
    "3. https://super-ai-components.vercel.app/llms.txt: items you have not installed yet.",
    "",
    "When the installed `.meta.json` and the web disagree, the installed file wins on conflict.",
    "",
  );
  return parts.join("\n");
}

const SHIM_SOURCE = `// Generated by Super AI Components agent-kit-hooks. Do not edit; reinstall to update.
// Lets any PreToolUse hook that loads scripts/check-tokens.mjs run the kit's rules.
export { lintText } from "./super-ai/validate.mjs";
`;

const HOOK_SOURCE = `#!/usr/bin/env node
// Generated by Super AI Components agent-kit-hooks. Do not edit; reinstall to update.
// PreToolUse on Write|Edit|MultiEdit: blocks an edit that introduces a token
// blocker, before it is written. Fails open: any error exits 0.
import { readFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

function candidateText(tool, input) {
  if (tool === "Write") return String(input.content ?? "");
  if (tool === "Edit") return String(input.new_string ?? "");
  if (tool === "MultiEdit") return (input.edits ?? []).map((e) => String(e?.new_string ?? "")).join("\\n");
  return "";
}

async function main() {
  const payload = JSON.parse(readFileSync(0, "utf8"));
  const input = payload.tool_input ?? {};
  if (!input.file_path) return;
  const text = candidateText(payload.tool_name ?? "", input);
  if (!text.trim()) return;
  const rel = relative(ROOT, resolve(input.file_path)).split("\\\\").join("/");
  if (rel.startsWith("..")) return;
  const { lintText } = await import("../../scripts/super-ai/validate.mjs");
  const findings = lintText(rel, text);
  if (!findings.length) return;
  const detail = findings.map((f) => \`  - \${f.why}: \${f.values.join(", ")}\`).join("\\n");
  process.stderr.write(
    \`Super AI token gate: this edit introduces \${findings.length} violation(s):\\n\${detail}\\n\\n\` +
      "Use the theme's semantic utilities. If no token fits, ask the human before adding one (rule 5).\\n",
  );
  process.exit(2);
}

main().catch(() => process.exit(0));
`;

export interface KitInput {
  records: KitRule[];
  sources: Record<string, string>;
}

/** Reads the rule records and runtime sources from disk. */
export function loadKitInput(): KitInput {
  const records = readdirSync(join(REPO_ROOT, RULES_DIR))
    .filter((f) => f.endsWith(".json"))
    .sort()
    .flatMap((f) => JSON.parse(readFileSync(join(REPO_ROOT, RULES_DIR, f), "utf8")).rules as KitRule[]);
  const sources = Object.fromEntries(
    Object.values(KIT_SOURCES).map((src) => [src, readFileSync(join(REPO_ROOT, src), "utf8")]),
  );
  return { records, sources };
}

/** Every kit file, keyed by its path under apps/docs. */
export function agentKitFiles(
  input: KitInput & { toon: string; rules?: readonly ConsumerRule[] },
): Map<string, string> {
  const files = new Map<string, string>();
  const at = (rel: string, content: string) => files.set(`${KIT_DIR}/${rel}`, content);
  at("AGENTS.super-ai.md", renderAgentsFile(input.rules ?? CONSUMER_RULES));
  at("index.toon", input.toon);
  for (const [target, src] of Object.entries(KIT_SOURCES)) at(target, input.sources[src]);
  at(
    "scripts/super-ai/rules.json",
    `${JSON.stringify({ version: 1, rules: consumerRules(input.records) }, null, 2)}\n`,
  );
  at("scripts/check-tokens.mjs", SHIM_SOURCE);
  at("hooks/super-ai-guard.mjs", HOOK_SOURCE);
  return files;
}
