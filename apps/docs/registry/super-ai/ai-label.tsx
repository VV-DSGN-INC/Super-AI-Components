import { Sparkles, type LucideIcon } from "lucide-react";
import * as React from "react";

import { Badge } from "@/components/ui/badge";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { cn } from "@/lib/utils";

/**
 * The one glyph that means "AI acted here". Consumers reuse this constant
 * instead of importing `Sparkles` themselves, so a change of mark is one edit.
 */
export const AI_LABEL_ICON: LucideIcon = Sparkles;

type AiLabelVariant = "generated" | "edited" | "summarized" | "sender" | "after-handoff" | "text-tint";

/**
 * Chip text is one word or two and names what happened to the content, never a
 * bare "AI". `sentence` is the start of the accessible name, which is longer
 * than the chip on purpose.
 */
const COPY: Record<AiLabelVariant, { text: string; sentence: string }> = {
  generated: { text: "Generated", sentence: "Generated by AI" },
  edited: { text: "Edited", sentence: "Edited by AI" },
  summarized: { text: "Summarized", sentence: "Summarized by AI" },
  sender: { text: "AI reply", sentence: "Reply written by AI" },
  "after-handoff": { text: "Handed off", sentence: "AI replies ended here, a person took over" },
  "text-tint": { text: "", sentence: "Text written by AI" },
};

interface AiLabelProps extends Omit<React.ComponentProps<"span">, "children"> {
  /** What the AI did. `text-tint` wraps AI-sourced prose instead of drawing a chip. */
  variant?: AiLabelVariant;
  /** Model or agent name, appended to the accessible name: "Generated by AI, Claude". */
  by?: string;
  /** When it happened, already formatted: "3 minutes ago". */
  at?: string;
  /** Extra detail shown in the tooltip, as plain text. */
  detail?: string;
  /** Chip: overrides the chip text. `text-tint`: the AI-sourced prose itself. */
  children?: React.ReactNode;
}

function AiLabel({ variant = "generated", by, at, detail, children, className, ...props }: AiLabelProps) {
  const { text, sentence } = COPY[variant];
  const name = [sentence, by, at].filter(Boolean).join(", ");

  if (variant === "text-tint") {
    return (
      <span
        data-slot="ai-label"
        data-variant={variant}
        role="group"
        aria-label={name}
        // The tint is the foreground token at a pinned step, so it passes on
        // the page background by itself. It never leans on a muted surface.
        className={cn("text-foreground/70", className)}
        {...props}
      >
        {children}
      </span>
    );
  }

  const chipProps = {
    "data-slot": "ai-label",
    "data-variant": variant,
    role: "note",
    "aria-label": name,
    variant: "outline" as const,
    className: cn(variant === "after-handoff" && "border-dashed", className),
    ...props,
  };
  const content = (
    <>
      <AI_LABEL_ICON aria-hidden data-slot="ai-label-icon" />
      <span data-slot="ai-label-text">{children ?? text}</span>
    </>
  );

  // The tooltip exists only when there is something beyond the chip text to
  // say. A bare chip takes no tab stop.
  if (!by && !at && !detail) {
    return <Badge {...chipProps}>{content}</Badge>;
  }

  return (
    <Tooltip>
      <TooltipTrigger data-slot="ai-label" render={<Badge {...chipProps} tabIndex={0} />}>
        {content}
      </TooltipTrigger>
      <TooltipContent
        side="top"
        className="motion-reduce:data-open:animate-none motion-reduce:data-closed:animate-none"
      >
        <span data-slot="ai-label-detail" className="flex flex-col">
          <span>{name}</span>
          {detail ? <span>{detail}</span> : null}
        </span>
      </TooltipContent>
    </Tooltip>
  );
}

export { AiLabel };
export type { AiLabelProps, AiLabelVariant };
