import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it } from "vitest";
import { expectAccessibleName } from "@/lib/test-utils";
import { Sparkles } from "lucide-react";
import { AI_LABEL_ICON, AiLabel } from "./ai-label";

const chip = () => document.querySelector('[data-slot="ai-label"]') as HTMLElement;

describe("AiLabel", () => {
  it("renders the generated state", () => {
    render(<AiLabel variant="generated" />);
    expect(chip()).toHaveTextContent("Generated");
    expect(chip()).toHaveAttribute("role", "note");
    expectAccessibleName(chip(), "Generated by AI");
  });

  it("renders the edited state", () => {
    render(<AiLabel variant="edited" />);
    expect(chip()).toHaveTextContent("Edited");
    expectAccessibleName(chip(), "Edited by AI");
  });

  it("renders the summarized state", () => {
    render(<AiLabel variant="summarized" />);
    expect(chip()).toHaveTextContent("Summarized");
    expectAccessibleName(chip(), "Summarized by AI");
  });

  it("renders the sender state, never a bare AI", () => {
    render(<AiLabel variant="sender" />);
    expect(chip()).toHaveTextContent("AI reply");
    expect(chip().textContent?.trim()).not.toBe("AI");
    expectAccessibleName(chip(), "Reply written by AI");
  });

  it("renders the after-handoff state with a dashed border as the non-colour cue", () => {
    render(<AiLabel variant="after-handoff" />);
    expect(chip()).toHaveTextContent("Handed off");
    expect(chip().className).toContain("border-dashed");
    expectAccessibleName(chip(), "AI replies ended here, a person took over");
  });

  it("renders the text-tint state as a labelled wrapper around prose", () => {
    render(<AiLabel variant="text-tint">The rewrite keeps the original structure.</AiLabel>);
    expect(chip()).toHaveAttribute("role", "group");
    expect(chip()).toHaveTextContent("The rewrite keeps the original structure.");
    expectAccessibleName(chip(), "Text written by AI");
  });

  it("tints with the foreground token on its own, never a muted surface", () => {
    render(<AiLabel variant="text-tint">prose</AiLabel>);
    expect(chip().className).toContain("text-foreground/70");
    expect(chip().className).not.toMatch(/muted|bg-/);
  });

  it("builds the accessible name from the full sentence, not the chip text", () => {
    render(<AiLabel variant="generated" by="Claude" at="3 minutes ago" />);
    expectAccessibleName(chip(), "Generated by AI, Claude, 3 minutes ago");
    expect(chip()).toHaveTextContent("Generated");
  });

  it("lets children override the chip text without changing the accessible name", () => {
    render(<AiLabel variant="edited">Rewrote</AiLabel>);
    expect(chip()).toHaveTextContent("Rewrote");
    expectAccessibleName(chip(), "Edited by AI");
  });

  it("takes no tab stop when there is nothing beyond the chip text", () => {
    render(<AiLabel variant="generated" />);
    expect(chip()).not.toHaveAttribute("tabindex");
  });

  it("takes one tab stop and shows the detail in a tooltip when by, at or detail is set", async () => {
    const user = userEvent.setup();
    render(<AiLabel variant="generated" by="Claude" detail="Prompt version 4" />);
    expect(chip()).toHaveAttribute("tabindex", "0");
    await user.tab();
    expect(chip()).toHaveFocus();
    expect(await screen.findByText("Prompt version 4")).toBeInTheDocument();
  });

  it("hides the glyph from assistive tech and exports it for reuse", () => {
    render(<AiLabel variant="generated" />);
    expect(chip().querySelector("svg")).toHaveAttribute("aria-hidden", "true");
    expect(AI_LABEL_ICON).toBe(Sparkles);
  });

  it("passes className through on the chip and on the tint wrapper", () => {
    const { rerender } = render(<AiLabel className="test-class" />);
    expect(chip().className).toContain("test-class");
    rerender(<AiLabel variant="text-tint" className="test-class" />);
    expect(chip().className).toContain("test-class");
  });
});
