import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it } from "vitest";
import { expectAccessibleName } from "@/lib/test-utils";
import { ContentCredentials, type ContentCredentialsRecord } from "./content-credentials";

const VERIFIED: ContentCredentialsRecord = {
  status: "verified",
  issuer: "Example Issuer CA",
  model: "Flux 1.1 Pro",
  generatedAt: "2026-10-12T09:30:00Z",
};

function panel() {
  return document.querySelector<HTMLElement>('[data-slot="content-credentials-panel"]');
}

describe("ContentCredentials", () => {
  it("renders the verified state: signature copy plus issuer, model and time through the stat grid", () => {
    render(<ContentCredentials credentials={VERIFIED} defaultOpen />);
    expect(panel()!.getAttribute("data-status")).toBe("verified");
    expect(screen.getByText("Credentials verified")).toBeInTheDocument();
    expect(screen.getByText("Publisher").nextElementSibling).toHaveTextContent("Example Issuer CA");
    expect(screen.getByText("Model").nextElementSibling).toHaveTextContent("Flux 1.1 Pro");
    expect(screen.getByText("Generated").nextElementSibling).toHaveTextContent("Oct 12, 2026, 09:30 UTC");
    expect(document.querySelector('[data-slot="stat-readout"]')).toBeInTheDocument();
  });

  it("renders the unverified state: metadata stays, but the publisher is a claim", () => {
    render(<ContentCredentials credentials={{ ...VERIFIED, status: "unverified" }} defaultOpen />);
    expect(screen.getByText("Credentials could not be verified")).toBeInTheDocument();
    expect(screen.getByText(/signature failed/)).toBeInTheDocument();
    expect(screen.queryByText("Publisher")).not.toBeInTheDocument();
    expect(screen.getByText("Claimed publisher")).toBeInTheDocument();
    expect(screen.getByText("Flux 1.1 Pro")).toBeInTheDocument();
  });

  it("renders the stripped state as removed credentials, never as human-made", () => {
    render(
      <ContentCredentials
        credentials={{ status: "stripped", issuer: "ignored", model: "ignored", origin: "ai-generated" }}
        defaultOpen
      />,
    );
    expect(screen.getByText("Credentials removed")).toBeInTheDocument();
    expect(panel()!.textContent).toMatch(/does not mean a person made it/);
    // Nothing is claimed from a record that no longer exists.
    expect(screen.queryByText("ignored")).not.toBeInTheDocument();
    expect(screen.queryByText("Generated by AI")).not.toBeInTheDocument();
    expect(document.querySelector('[data-slot="stat-readout"]')).toBeNull();
  });

  it("keeps verified, unverified and stripped copy distinct", () => {
    const bodies = (["verified", "unverified", "stripped"] as const).map((status) => {
      const { unmount } = render(<ContentCredentials credentials={{ status }} defaultOpen />);
      const text = document.querySelector('[data-slot="content-credentials-note"]')!.textContent;
      unmount();
      return text;
    });
    expect(new Set(bodies).size).toBe(3);
  });

  it("renders the ai-generated state", () => {
    render(<ContentCredentials credentials={{ ...VERIFIED, origin: "ai-generated" }} defaultOpen />);
    expect(screen.getByText("AI use").nextElementSibling).toHaveTextContent("Generated by AI");
  });

  it("renders the ai-edited state", () => {
    render(<ContentCredentials credentials={{ ...VERIFIED, origin: "ai-edited" }} defaultOpen />);
    expect(screen.getByText("AI use").nextElementSibling).toHaveTextContent("Edited with AI");
  });

  it("renders the with-history state as an ordered list, in the order given, each step attributed", () => {
    render(
      <ContentCredentials
        defaultOpen
        credentials={{
          ...VERIFIED,
          origin: "ai-edited",
          edits: [
            { action: "Generated", by: "Flux 1.1 Pro", at: "2026-10-12T09:30:00Z" },
            { action: "Cropped", by: "Crop tool" },
            { action: "Generative fill", by: "Firefly", at: "2026-10-12T10:05:00Z" },
          ],
        }}
      />,
    );
    const items = document.querySelectorAll('[data-slot="content-credentials-edit"]');
    expect([...items].map((li) => li.textContent)).toEqual([
      expect.stringContaining("Generated by Flux 1.1 Pro"),
      "Cropped by Crop tool",
      expect.stringContaining("Generative fill by Firefly"),
    ]);
    expect(items[0]!.parentElement!.tagName).toBe("OL");
  });

  it("omits the history section when there are no edits", () => {
    render(<ContentCredentials credentials={VERIFIED} defaultOpen />);
    expect(document.querySelector('[data-slot="content-credentials-history"]')).toBeNull();
  });

  it("falls back to the raw string for a timestamp it cannot parse", () => {
    render(<ContentCredentials credentials={{ ...VERIFIED, generatedAt: "last Tuesday" }} defaultOpen />);
    expect(screen.getByText("Generated").nextElementSibling).toHaveTextContent("last Tuesday");
  });

  it("opens the hover-card on keyboard focus, not only on hover", async () => {
    render(<ContentCredentials credentials={VERIFIED} trigger="hover-card" />);
    expect(panel()).toBeNull();
    await userEvent.tab();
    expect(await screen.findByText("Credentials verified")).toBeInTheDocument();
  });

  it("opens the popover on click and names the panel by its heading", async () => {
    render(<ContentCredentials credentials={VERIFIED} trigger="popover" />);
    expect(panel()).toBeNull();
    await userEvent.click(screen.getByRole("button", { name: /Verified/ }));
    const dialog = await screen.findByRole("dialog");
    expectAccessibleName(dialog, "Credentials verified");
  });

  it("describes the mark with the verdict, so it is known before the panel opens", () => {
    render(<ContentCredentials credentials={{ ...VERIFIED, origin: "ai-generated" }} />);
    const mark = screen.getByRole("button");
    const describedBy = mark.getAttribute("aria-describedby")!;
    expect(document.getElementById(describedBy)).toHaveTextContent(
      "Content credentials: verified. Generated by AI.",
    );
  });

  it("uses a consumer mark as the trigger when children are given", () => {
    render(
      <ContentCredentials credentials={VERIFIED}>
        <button type="button">AI-generated</button>
      </ContentCredentials>,
    );
    expect(screen.getAllByRole("button")).toHaveLength(1);
    expect(screen.getByRole("button", { name: "AI-generated" })).toHaveAttribute("aria-describedby");
  });

  it("passes className through", () => {
    render(<ContentCredentials credentials={VERIFIED} className="test-class" />);
    expect(document.querySelector('[data-slot="content-credentials"]')!.className).toContain("test-class");
  });
});
