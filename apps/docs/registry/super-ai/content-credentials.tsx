"use client";

import { ShieldAlert, ShieldCheck, ShieldOff } from "lucide-react";
import * as React from "react";

import { HoverCard, HoverCardContent, HoverCardTrigger } from "@/components/ui/hover-card";
import { Popover, PopoverContent, PopoverTitle, PopoverTrigger } from "@/components/ui/popover";
import { cn } from "@/lib/utils";
import { StatReadout, type StatReadoutItem } from "@/registry/super-ai/stat-readout";

/**
 * Content Credentials — The provenance panel behind an AI label: model, time, edits, publisher, and whether it verifies.
 *
 * Spec: docs/design-system/component-specs.md#n16-content-credentials
 * States: verified · unverified · stripped · ai-generated · ai-edited · with-history
 *
 * Standards named, not implemented: C2PA Content Credentials is the metadata
 * shape `credentials` is modelled on. This component renders a typed record
 * and never parses a file; reading and verifying a manifest is the host's job.
 *
 * Three load-bearing sentences from the spec, enforced here:
 *
 * - `verified`, `unverified` and `stripped` are three different claims with
 *   three different copy blocks. `stripped` is not "human-made": it says the
 *   credentials are gone and that nothing can be inferred either way.
 * - `unverified` still shows the metadata, but labels the publisher as a claim,
 *   because a failed signature means the fields may have been altered.
 * - `with-history` renders the edit list in the order given, each step
 *   attributed. The component never re-sorts it.
 *
 * Base: HoverCard and Popover (components/ui, Base UI) and A10 `stat-readout`
 * for the key-value grid, the same grid F3 `asset-detail` and N5
 * `run-inspector` use.
 */

type CredentialsStatus = "verified" | "unverified" | "stripped";

/** How AI took part, per C2PA's digital source type. Independent of `status`. */
type CredentialsOrigin = "ai-generated" | "ai-edited";

interface CredentialsEdit {
  /** What was done, e.g. "Generative fill". */
  action: string;
  /** Who or what did it: a person, a tool or a model. */
  by: string;
  /** ISO 8601 timestamp. Shown in UTC. */
  at?: string;
}

interface ContentCredentialsRecord {
  /**
   * `verified`: the signature checked out. `unverified`: metadata is present
   * but the signature failed. `stripped`: the credentials were removed, so
   * every other field is ignored.
   */
  status: CredentialsStatus;
  origin?: CredentialsOrigin;
  /** The publisher or signing issuer. */
  issuer?: string;
  /** The generating model. */
  model?: string;
  /** ISO 8601 timestamp of generation. Shown in UTC. */
  generatedAt?: string;
  /** Ordered oldest first, as the manifest records them. */
  edits?: CredentialsEdit[];
}

interface ContentCredentialsProps extends Omit<React.ComponentProps<"span">, "children"> {
  credentials: ContentCredentialsRecord;
  /**
   * `hover-card` for a mark on a result tile; it opens on pointer hover and on
   * keyboard focus. `popover` for a click target.
   */
  trigger?: "hover-card" | "popover";
  /** The mark that opens the panel, e.g. an A13 label. Omit for the built-in status chip. */
  children?: React.ReactElement;
  open?: boolean;
  defaultOpen?: boolean;
  onOpenChange?: (open: boolean) => void;
}

const STATUS_COPY: Record<CredentialsStatus, { chip: string; title: string; body: string }> = {
  verified: {
    chip: "Verified",
    title: "Credentials verified",
    body: "The signature checks out against the issuer, so these details are as the issuer recorded them. This does not say the content is accurate.",
  },
  unverified: {
    chip: "Unverified",
    title: "Credentials could not be verified",
    body: "Credentials are attached but the signature failed. The details below may have been altered, so read them as a claim rather than a record.",
  },
  stripped: {
    chip: "No credentials",
    title: "Credentials removed",
    body: "The provenance data was removed or never attached. That says nothing about how this was made. It does not mean a person made it.",
  },
};

const ORIGIN_COPY: Record<CredentialsOrigin, string> = {
  "ai-generated": "Generated by AI",
  "ai-edited": "Edited with AI",
};

const STATUS_ICON = {
  verified: ShieldCheck,
  unverified: ShieldAlert,
  stripped: ShieldOff,
} as const;

/** Fixed locale and zone so the same record reads the same everywhere. */
function formatWhen(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return `${date.toLocaleString("en-US", {
    timeZone: "UTC",
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  })} UTC`;
}

function summaryOf(credentials: ContentCredentialsRecord): string {
  const parts = [`Content credentials: ${STATUS_COPY[credentials.status].chip.toLowerCase()}`];
  if (credentials.status !== "stripped" && credentials.origin) parts.push(ORIGIN_COPY[credentials.origin]);
  return `${parts.join(". ")}.`;
}

function buildItems(credentials: ContentCredentialsRecord): StatReadoutItem[] {
  const items: StatReadoutItem[] = [];
  if (credentials.origin) items.push({ label: "AI use", value: ORIGIN_COPY[credentials.origin] });
  if (credentials.issuer !== undefined) {
    // A failed signature turns the publisher from a fact into a claim.
    items.push({
      label: credentials.status === "unverified" ? "Claimed publisher" : "Publisher",
      value: credentials.issuer,
    });
  }
  if (credentials.model !== undefined) items.push({ label: "Model", value: credentials.model });
  if (credentials.generatedAt !== undefined) {
    items.push({ label: "Generated", value: formatWhen(credentials.generatedAt) });
  }
  return items;
}

function PopoverHeading(props: React.ComponentProps<"h3">) {
  // Wires the popup's aria-labelledby to the same heading the hover-card form renders.
  return <PopoverTitle render={<h3 />} {...props} />;
}

function PanelBody({
  credentials,
  Title,
}: {
  credentials: ContentCredentialsRecord;
  Title: React.ElementType;
}) {
  const copy = STATUS_COPY[credentials.status];
  const Icon = STATUS_ICON[credentials.status];
  const stripped = credentials.status === "stripped";
  const items = stripped ? [] : buildItems(credentials);
  const edits = stripped ? [] : (credentials.edits ?? []);

  return (
    <div
      data-slot="content-credentials-panel"
      data-status={credentials.status}
      className="flex flex-col gap-2.5 break-words"
    >
      <div className="flex items-center gap-1.5">
        <Icon aria-hidden="true" className="size-4 shrink-0" />
        <Title data-slot="content-credentials-title" className="text-sm font-medium">
          {copy.title}
        </Title>
      </div>
      <p data-slot="content-credentials-note" className="text-foreground text-xs">
        {copy.body}
      </p>
      {items.length > 0 ? <StatReadout items={items} columns={2} className="text-xs" /> : null}
      {edits.length > 0 ? (
        <div data-slot="content-credentials-history" className="flex flex-col gap-1">
          <p className="text-xs font-medium">Edit history</p>
          <ol className="flex list-decimal flex-col gap-1 ps-4 text-xs">
            {edits.map((edit, i) => (
              <li key={i} data-slot="content-credentials-edit">
                <span className="font-medium">{edit.action}</span> by {edit.by}
                {edit.at ? <span className="block">{formatWhen(edit.at)}</span> : null}
              </li>
            ))}
          </ol>
        </div>
      ) : null}
    </div>
  );
}

function ContentCredentials({
  credentials,
  trigger = "hover-card",
  children,
  open,
  defaultOpen,
  onOpenChange,
  className,
  ...props
}: ContentCredentialsProps) {
  const summaryId = React.useId();
  const copy = STATUS_COPY[credentials.status];
  const Icon = STATUS_ICON[credentials.status];

  const mark = children ?? (
    <button
      type="button"
      data-slot="content-credentials-mark"
      className="border-border text-foreground focus-visible:ring-ring inline-flex items-center gap-1 rounded-md border px-1.5 py-0.5 text-xs font-medium focus-visible:ring-2 focus-visible:outline-none"
    >
      <Icon aria-hidden="true" className="size-3.5 shrink-0" />
      {copy.chip}
    </button>
  );

  const rootProps = { open, defaultOpen, onOpenChange };

  return (
    <span
      data-slot="content-credentials"
      data-trigger={trigger}
      className={cn("inline-flex", className)}
      {...props}
    >
      {/* The panel is a portal that only exists while open, so the verdict
          is carried here for the mark to be described by. */}
      <span id={summaryId} className="sr-only">
        {summaryOf(credentials)}
      </span>
      {trigger === "popover" ? (
        <Popover {...rootProps}>
          <PopoverTrigger render={mark} aria-describedby={summaryId} />
          <PopoverContent className="w-80 max-w-[calc(100vw-2rem)]">
            <PanelBody credentials={credentials} Title={PopoverHeading} />
          </PopoverContent>
        </Popover>
      ) : (
        <HoverCard {...rootProps}>
          <HoverCardTrigger render={mark} aria-describedby={summaryId} />
          <HoverCardContent className="w-80 max-w-[calc(100vw-2rem)]">
            <PanelBody credentials={credentials} Title="h3" />
          </HoverCardContent>
        </HoverCard>
      )}
    </span>
  );
}

export { ContentCredentials };
export type {
  ContentCredentialsEdit,
  ContentCredentialsProps,
  ContentCredentialsRecord,
  CredentialsOrigin,
  CredentialsStatus,
};
